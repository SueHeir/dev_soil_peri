#!/usr/bin/env python3
"""Independently check the validated fracture case under a 1-vs-2 rank split.

This is deliberately a two-part experiment.  First, ``verify.py`` must pass its
published Ha--Bobaru trajectory and Griffith checks on a fresh serial run.
Only then do we compare fresh MPI runs of the *same* geometry, material,
timestep, loading, and number of steps.  The two-rank input is generated by
changing only ``[comm].processors_x``; it is not a second hand-tuned case.

The comparison does not treat rank one as a physics reference.  It checks
whether decomposing an already externally anchored calculation changes its
global trajectory.  Crack-tip lattice position and cracked-point count are
discrete observables and must agree exactly on every reported row.  Damage and
kinetic-energy reductions may reorder floating-point additions, so their bound
is ``4096 * eps * max(1, |a|, |b|)``.  That is a stated f64 round-off envelope,
not a fit to this run; no physical tolerance is loosened here.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
EXAMPLE = "bb_plate_fracture"
CONFIG = HERE / "config.toml"
ROWS = re.compile(
    r"CRACKROW step=(\d+) time=([-+0-9.eE]+) tip_x=([-+0-9.eE]+) "
    r"n_crack=(\d+) sum_damage=([-+0-9.eE]+) ke=([-+0-9.eE]+)"
)
REDUCTION_FACTOR = 4096.0


def run(command, *, timeout=900):
    return subprocess.run(command, cwd=REPO, text=True, capture_output=True, timeout=timeout)


def require_ok(result, label):
    if result.returncode:
        print(result.stdout[-4000:])
        print(result.stderr[-4000:])
        raise SystemExit(f"{label} failed")


def parse_rows(output):
    rows = {}
    for match in ROWS.finditer(output):
        step = int(match.group(1))
        rows[step] = {
            "time": float(match.group(2)),
            "tip_x": float(match.group(3)),
            "n_crack": int(match.group(4)),
            "sum_damage": float(match.group(5)),
            "ke": float(match.group(6)),
        }
    if not rows:
        raise SystemExit("no full-precision CRACKROW diagnostics found")
    return rows


def reduction_bound(a, b):
    return REDUCTION_FACTOR * sys.float_info.epsilon * max(1.0, abs(a), abs(b))


def mpi_config(path):
    text = CONFIG.read_text(encoding="utf-8")
    updated, count = re.subn(r"(?m)^processors_x\s*=\s*1\s*$", "processors_x = 2", text, count=1)
    if count != 1:
        raise SystemExit("could not change exactly one processors_x setting")
    path.write_text(updated, encoding="utf-8")


def run_case(mpirun, ranks, config):
    executable = REPO / "target" / "release" / "examples" / EXAMPLE
    result = run([mpirun, "-np", str(ranks), str(executable), str(config)])
    require_ok(result, f"{ranks}-rank fracture run")
    return parse_rows(result.stdout + result.stderr)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, help="write measured rows and bounds as JSON")
    parser.add_argument("--reference-checked", action="store_true",
                        help="only for a driver that has just run verify.py successfully")
    args = parser.parse_args()

    # External-reference gate: run it, don't merely inspect a previous log.
    if not args.reference_checked:
        reference = run([sys.executable, str(HERE / "verify.py")], timeout=1800)
        require_ok(reference, "serial Ha--Bobaru/Griffith validation")
        if "ALL CHECKS PASSED" not in reference.stdout:
            raise SystemExit("serial reference validator did not report success")

    mpirun = shutil.which("mpirun") or shutil.which("mpiexec")
    if not mpirun:
        raise SystemExit("mpirun/mpiexec is required for this decomposition check")
    build = run(["cargo", "build", "--release", "--example", EXAMPLE])
    require_ok(build, "MPI example build")

    with tempfile.TemporaryDirectory(prefix="peri-decomposition-") as temp:
        two_config = Path(temp) / "config_2rank.toml"
        mpi_config(two_config)
        one = run_case(mpirun, 1, CONFIG)
        two = run_case(mpirun, 2, two_config)

    if set(one) != set(two):
        raise SystemExit(f"different diagnostic steps: 1={sorted(one)} 2={sorted(two)}")

    failures = []
    worst = {"sum_damage": (0.0, 0.0, None), "ke": (0.0, 0.0, None)}
    for step in sorted(one):
        a, b = one[step], two[step]
        for field in ("time", "tip_x", "n_crack"):
            if a[field] != b[field]:
                failures.append(f"step {step}: {field} differs ({a[field]!r} vs {b[field]!r})")
        for field in worst:
            delta = abs(a[field] - b[field])
            bound = reduction_bound(a[field], b[field])
            if delta > worst[field][0]:
                worst[field] = (delta, bound, step)
            if delta > bound:
                failures.append(
                    f"step {step}: {field} delta={delta:.17e} exceeds f64 bound={bound:.17e}"
                )

    print("--- dev_soil_peri fracture decomposition invariance ---")
    if args.reference_checked:
        print("PASS external serial Ha--Bobaru/Griffith validator (fresh driver gate)")
    else:
        print("PASS external serial Ha--Bobaru/Griffith validator")
    print(f"compared {len(one)} full-precision rows")
    for field, (delta, bound, step) in worst.items():
        print(f"{field}: max delta={delta:.17e}, bound={bound:.17e}, step={step}")
    if failures:
        print("FAIL exact/reduction checks:")
        print("\n".join(failures[:20]))
        raise SystemExit(1)
    if args.report:
        args.report.write_text(json.dumps({
            "rank_pair": [1, 2],
            "external_reference_gate": "Ha--Bobaru/Griffith validator passed",
            "reduction_bound": "4096 * f64 epsilon * max(1, |a|, |b|)",
            "exact_fields": ["time", "tip_x", "n_crack"],
            "rows": [{"step": step, "one": one[step], "two": two[step]}
                     for step in sorted(one)],
            "max_abs_difference": {field: {"value": delta, "bound": bound, "step": step}
                                   for field, (delta, bound, step) in worst.items()},
        }, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {args.report}")
    print("PASS exact time/tip_x/n_crack; PASS stated f64 reduction envelopes")


if __name__ == "__main__":
    main()
